import json
import os
import shutil
from importlib import resources
from typing import Any

from nld.docs.models import DocsSiteConfig, ProjectSnapshot

ASSET_PACKAGE: str = "nld.docs.site.assets"

ASSET_FILE_NAMES: tuple[str, ...] = (
    "index.html",
    "styles.css",
    "app.js",
    "nld_mark.svg",
    "nld_avatar.svg",
)

SNAPSHOT_JSON_FILE_NAME: str = "snapshot.json"
SITE_CONFIG_FILE_NAME: str = "docs.config.json"
SITE_CONFIG_SCRIPT_FILE_NAME: str = "docs.config.js"
STATE_JSON_FILE_NAME: str = "state.json"
SNAPSHOT_SCRIPT_FILE_NAME: str = "snapshot.js"
LAUNCHER_FILE_NAME: str = "serve.py"
README_FILE_NAME: str = "README.md"

LAUNCHER_TEMPLATE: str = '''"""Serve this generated nld documentation site.

Run ``python serve.py`` from this folder, then open the printed URL. This
launcher serves the static export only; run ``nld docs serve`` from the
project to get the live-state API as well.
"""

import http.server
import os
import socketserver

PORT = int(os.environ.get("NLD_DOCS_PORT", "8765"))

if __name__ == "__main__":
    os.chdir(os.path.dirname(os.path.abspath(__file__)))
    handler = http.server.SimpleHTTPRequestHandler
    with socketserver.TCPServer(("127.0.0.1", PORT), handler) as httpd:
        print(f"nld docs available on http://127.0.0.1:{PORT}/")
        httpd.serve_forever()
'''

README_TEMPLATE: str = """<img src="./nld_avatar.svg" alt="NexusLab Data" width="96" />

# {project_name} — nld documentation

Generated by `nld docs` on {generated_at} from the project assets.

- Open `index.html` directly, or run `python serve.py` and browse to the
  printed URL.
- `snapshot.json` is the machine-readable document this site renders; it is
  versioned (`schema_version` {schema_version}) and diffable between commits
  once its `meta` block (build time, generator version) is ignored.
- This export has no live-state layer: the "Live state" page needs the
  project's backends and is only served by `nld docs serve` from the project
  itself.
"""


class DocsSiteBuilder:
    """Writes the deployable documentation site to a target folder.

    The site is deliberately buildless: the template ships with the package
    and the snapshot is embedded as a JavaScript assignment, so the export
    also opens from ``file://`` where ``fetch`` is blocked.
    """

    def __init__(
        self,
        target_folder_path: str,
    ) -> None:
        self.target_folder_path = target_folder_path

    def build(
        self,
        snapshot: ProjectSnapshot,
        with_launcher: bool = False,
        config: DocsSiteConfig | None = None,
    ) -> list[str]:
        """Write the site and return the paths it created."""
        os.makedirs(self.target_folder_path, exist_ok=True)
        written: list[str] = []

        for file_name in ASSET_FILE_NAMES:
            source = resources.files(ASSET_PACKAGE).joinpath(file_name)
            destination = os.path.join(self.target_folder_path, file_name)
            with resources.as_file(source) as source_path:
                shutil.copyfile(source_path, destination)
            written.append(destination)

        written.append(self._write_snapshot(snapshot=snapshot))
        written.append(self._write_snapshot_script(snapshot=snapshot))
        written.extend(
            self.write_config(
                config=config
                if config is not None
                else DocsSiteConfig(project_name=snapshot.project.name),
            )
        )

        if with_launcher:
            written.append(self._write_launcher())
            written.append(self._write_readme(snapshot=snapshot))

        return written

    def write_config(
        self,
        config: DocsSiteConfig,
    ) -> list[str]:
        """Write the site configuration, as a file and as a script.

        The script is what a site opened from ``file://`` reads, where
        ``fetch`` is blocked; the JSON file is what a host, a CI job or an
        operator edits to repoint a published site at another state source
        without rebuilding it.
        """
        os.makedirs(self.target_folder_path, exist_ok=True)
        payload = json.dumps(
            config.model_dump(mode="json"),
            indent=2,
            ensure_ascii=False,
            default=str,
        )
        config_path = os.path.join(self.target_folder_path, SITE_CONFIG_FILE_NAME)
        with open(config_path, "w", encoding="utf-8") as file_handle:
            file_handle.write(payload + "\n")

        script_path = os.path.join(
            self.target_folder_path,
            SITE_CONFIG_SCRIPT_FILE_NAME,
        )
        with open(script_path, "w", encoding="utf-8") as file_handle:
            file_handle.write("window.NLD_DOCS_CONFIG = " + payload + ";\n")

        return [config_path, script_path]

    def write_state(
        self,
        state: Any,
    ) -> str:
        """Write a collected live state beside the site.

        A published site has no API to call, so a scheduled job writes the
        state it collected here and the page reads it as a file.
        """
        os.makedirs(self.target_folder_path, exist_ok=True)
        path = os.path.join(self.target_folder_path, STATE_JSON_FILE_NAME)
        with open(path, "w", encoding="utf-8") as file_handle:
            file_handle.write(
                json.dumps(
                    state.model_dump(mode="json"),
                    indent=2,
                    ensure_ascii=False,
                    default=str,
                )
                + "\n"
            )
        return path

    def _snapshot_json(
        self,
        snapshot: ProjectSnapshot,
    ) -> str:
        """Serialise the snapshot the way both the file and the API do."""
        return json.dumps(
            snapshot.model_dump(mode="json"),
            indent=2,
            ensure_ascii=False,
            default=str,
        )

    def _write_snapshot(
        self,
        snapshot: ProjectSnapshot,
    ) -> str:
        """Write the machine-readable snapshot next to the site."""
        path = os.path.join(self.target_folder_path, SNAPSHOT_JSON_FILE_NAME)
        with open(path, "w", encoding="utf-8") as file_handle:
            file_handle.write(self._snapshot_json(snapshot=snapshot))
        return path

    def _write_snapshot_script(
        self,
        snapshot: ProjectSnapshot,
    ) -> str:
        """Embed the snapshot as a script so the export works offline."""
        path = os.path.join(self.target_folder_path, SNAPSHOT_SCRIPT_FILE_NAME)
        content = (
            "window.NLD_DOCS_SNAPSHOT = "
            + self._snapshot_json(snapshot=snapshot)
            + ";\n"
        )
        with open(path, "w", encoding="utf-8") as file_handle:
            file_handle.write(content)
        return path

    def _write_launcher(self) -> str:
        """Write the standalone launcher of the deployable site."""
        path = os.path.join(self.target_folder_path, LAUNCHER_FILE_NAME)
        with open(path, "w", encoding="utf-8") as file_handle:
            file_handle.write(LAUNCHER_TEMPLATE)
        return path

    def _write_readme(
        self,
        snapshot: ProjectSnapshot,
    ) -> str:
        """Write the deployment note shipped with the site."""
        path = os.path.join(self.target_folder_path, README_FILE_NAME)
        content = README_TEMPLATE.format(
            project_name=snapshot.project.name,
            generated_at=snapshot.meta.generated_at.isoformat(),
            schema_version=snapshot.schema_version,
        )
        with open(path, "w", encoding="utf-8") as file_handle:
            file_handle.write(content)
        return path
